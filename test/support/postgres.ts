import pg from 'pg';
import type { Row, SqlExecutor, SqlTx } from '../../src/index.js';

/**
 * Connection URL of the test database. `npm run db:up` starts one (compose.yaml)
 * on localhost:55432. Inside the dev container, TEST_POSTGRES_URL points at the
 * host instead (see .devcontainer/devcontainer.json).
 */
export const TEST_POSTGRES_URL =
  process.env['TEST_POSTGRES_URL'] ?? 'postgres://cypher:cypher@localhost:55432/cypher';

/** DDL for the generic layout with the default mapping, in the current schema. */
export const POSTGRES_SCHEMA = `
CREATE TABLE nodes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  labels jsonb NOT NULL CHECK (jsonb_typeof(labels) = 'array'),
  properties jsonb NOT NULL CHECK (jsonb_typeof(properties) = 'object')
);
CREATE TABLE edges (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  start_id bigint NOT NULL REFERENCES nodes (id),
  end_id bigint NOT NULL REFERENCES nodes (id),
  type text NOT NULL,
  properties jsonb NOT NULL CHECK (jsonb_typeof(properties) = 'object')
);
CREATE INDEX nodes_labels ON nodes USING gin (labels);
CREATE INDEX edges_start_id ON edges (start_id);
CREATE INDEX edges_end_id ON edges (end_id);
CREATE INDEX edges_type ON edges (type);
`;

export interface PostgresConnection {
  client: pg.Client;
  schema: string;
  /** Empties the graph and restarts ids. */
  reset: () => Promise<void>;
  /** Drops the schema and disconnects. */
  dispose: () => Promise<void>;
}

/**
 * Connects to the test database and creates a schema of its own (so test files
 * running in parallel do not share tables), with the generic layout in it.
 */
export async function connectPostgres(): Promise<PostgresConnection> {
  const client = new pg.Client({ connectionString: TEST_POSTGRES_URL });
  try {
    await client.connect();
  } catch (error) {
    throw new Error(
      `Cannot connect to PostgreSQL at ${TEST_POSTGRES_URL}. Start it with \`npm run db:up\`, ` +
        'or set TEST_POSTGRES_URL.',
      { cause: error },
    );
  }
  const schema = `test_${process.pid}_${Math.random().toString(36).slice(2, 8)}`;
  await client.query(`CREATE SCHEMA ${schema}`);
  await client.query(`SET search_path TO ${schema}`);
  await client.query(POSTGRES_SCHEMA);
  return {
    client,
    schema,
    reset: async (): Promise<void> => {
      await client.query('TRUNCATE edges, nodes RESTART IDENTITY');
    },
    dispose: async (): Promise<void> => {
      try {
        await client.query(`DROP SCHEMA ${schema} CASCADE`);
      } finally {
        await client.end();
      }
    },
  };
}

/**
 * Example executor over a `pg` client. Every step of a query runs in one
 * transaction; reads use REPEATABLE READ READ ONLY, so all steps see the same
 * snapshot and PostgreSQL itself refuses any write.
 */
export function postgresExecutor(client: pg.Client): SqlExecutor & { log: string[] } {
  const log: string[] = [];
  const tx: SqlTx = {
    async query(sql: string, values: unknown[]): Promise<Row[]> {
      log.push(sql);
      // 64-bit integers are bound as text; PostgreSQL casts them exactly.
      const params = values.map((v) => (typeof v === 'bigint' ? v.toString() : v));
      const result = await client.query(sql, params);
      return result.rows as Row[];
    },
  };
  return {
    log,
    async transaction<T>(mode: 'read' | 'write', fn: (tx: SqlTx) => Promise<T>): Promise<T> {
      await client.query(
        mode === 'read' ? 'BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY' : 'BEGIN',
      );
      try {
        const result = await fn(tx);
        await client.query('COMMIT');
        return result;
      } catch (error) {
        await client.query('ROLLBACK');
        throw error;
      }
    },
  };
}
