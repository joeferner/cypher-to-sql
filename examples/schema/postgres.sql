-- The generic layout with the default mapping (tables `nodes` and `edges`).
CREATE TABLE nodes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  labels jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(labels) = 'array'),
  properties jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(properties) = 'object')
);

CREATE TABLE edges (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  start_id bigint NOT NULL REFERENCES nodes (id),
  end_id bigint NOT NULL REFERENCES nodes (id),
  type text NOT NULL,
  properties jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(properties) = 'object')
);

-- Label predicates (`(n:Person)`) use `labels @> '["Person"]'`.
CREATE INDEX nodes_labels ON nodes USING gin (labels jsonb_path_ops);

-- Following relationships from either end, and filtering by type.
CREATE INDEX edges_start_id_type ON edges (start_id, type);
CREATE INDEX edges_end_id_type ON edges (end_id, type);
CREATE INDEX edges_type ON edges (type);
